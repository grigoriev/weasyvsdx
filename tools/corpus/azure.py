"""The Visio diagrams of the Azure Architecture Center, kept outside the repository.

Usage: azure.py list CHECKOUT    write corpus/azure.json from a checkout of MicrosoftDocs/architecture-center
       azure.py visio CHECKOUT   add the SVG that Visio exported of each diagram to corpus/azure.json
       azure.py fetch [--only TEXT]  download the diagrams of corpus/azure.json and their SVGs into the cache

The documentation links each diagram on arch-center.azureedge.net; the files are not in its repository, and
the Azure icons inside them may be copied for diagrams and documentation only. So the repository holds only
the list, with the SHA-256 of each file, and fetch keeps the files in the cache: WEASYVSDX_CACHE, by default
~/.cache/weasyvsdx. A file in the cache with the right hash is never downloaded again.

The article of a diagram shows it as an image, mostly an SVG that Visio exported, right above the link to
the diagram. That SVG is the reference of the bench closest to Visio: LibreOffice reads the drawing through
libvisio, as weasyvsdx does, and shares its errors. visio takes it at the commit of the checkout.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LIST = ROOT / "corpus" / "azure.json"
LINK = re.compile(r"https://arch-center\.azureedge\.net/[A-Za-z0-9._/-]+\.vsdx")
TIMEOUT = 60  # seconds per download
DOCS = "https://raw.githubusercontent.com/MicrosoftDocs/architecture-center/"
# An image of an article: the source of an image block or the target of a Markdown image
IMAGE = re.compile(r'source="([^"]+\.svg)"|!\[[^\]]*\]\(([^)\s]+\.svg)')
# The comment of Visio on the SVG it exports, "Generated by Microsoft Visio" or its translation, and its namespace
VISIO_MARKS = (b"Microsoft Visio", b"schemas.microsoft.com/visio")


def cache() -> Path:
    """The cache directory of the downloaded diagrams and their references."""
    return Path(os.environ.get("WEASYVSDX_CACHE") or Path.home() / ".cache" / "weasyvsdx")


def download(url: str) -> bytes:
    if not url.startswith(("https://arch-center.azureedge.net/", DOCS)):
        raise SystemExit(f"not a diagram of the Architecture Center: {url}")
    with urllib.request.urlopen(url, timeout=TIMEOUT) as response:
        data: bytes = response.read()
        return data


def name(url: str) -> str:
    """The corpus name of a diagram: azure- and its file name, without the suffix."""
    return "azure-" + url.rsplit("/", 1)[1].removesuffix(".vsdx")


def make_list(checkout: Path) -> int:
    """Every diagram the documentation links, with its hash, downloaded into the cache on the way."""
    docs = checkout / "docs"
    urls = sorted({match for path in docs.rglob("*") if path.suffix in (".md", ".yml") for match in LINK.findall(path.read_text(errors="replace"))})
    target = cache() / "azure"
    target.mkdir(parents=True, exist_ok=True)
    entries = []
    for url in urls:
        try:
            data = download(url)
        except OSError as e:
            print(f"{url}: {e}", file=sys.stderr)
            continue
        (target / f"{name(url)}.vsdx").write_bytes(data)
        entries.append({"name": name(url), "url": url, "sha256": hashlib.sha256(data).hexdigest()})
        print(f"{name(url)}: {len(data)} bytes", flush=True)
    LIST.write_text(json.dumps(entries, indent=1) + "\n")
    print(f"{len(entries)} of {len(urls)} diagrams in {LIST.relative_to(ROOT)}")
    return 0


def visio_svgs(checkout: Path) -> dict[str, str]:
    """The SVG of each diagram that Visio exported, by the URL of the diagram: the last one above its link."""
    found: dict[str, str] = {}
    for article in sorted((checkout / "docs").rglob("*.md")):
        text = article.read_text(errors="replace")
        for link in LINK.finditer(text):
            images = [first or second for first, second in IMAGE.findall(text[: link.start()])]
            if not images:
                continue
            svg = (article.parent / images[-1]).resolve()
            if svg.is_relative_to(checkout.resolve()) and svg.is_file() and any(mark in svg.read_bytes()[:2000] for mark in VISIO_MARKS):
                found.setdefault(link.group(0), svg.relative_to(checkout.resolve()).as_posix())
    return found


def add_visio(checkout: Path) -> int:
    """Each diagram of the list with the SVG of Visio its article shows, at the commit of the checkout."""
    commit = subprocess.run(["git", "-C", str(checkout), "rev-parse", "HEAD"], capture_output=True, text=True, check=True).stdout.strip()
    svgs = visio_svgs(checkout)
    entries = json.loads(LIST.read_text())
    for entry in entries:
        entry.pop("visio", None)
        if entry["url"] in svgs:
            path = svgs[entry["url"]]
            entry["visio"] = {"url": f"{DOCS}{commit}/{path}", "sha256": hashlib.sha256((checkout / path).read_bytes()).hexdigest()}
    LIST.write_text(json.dumps(entries, indent=1) + "\n")
    print(f"{sum(1 for entry in entries if 'visio' in entry)} of {len(entries)} diagrams have an SVG of Visio")
    return 0


def fetched(url: str, sha256: str, path: Path, label: str) -> bool:
    """Whether the cache holds the file of the hash at path, downloaded where it lacks it."""
    if path.exists() and hashlib.sha256(path.read_bytes()).hexdigest() == sha256:
        return True
    try:
        data = download(url)
    except OSError as e:
        print(f"{label}: {e}", file=sys.stderr)
        return False
    if hashlib.sha256(data).hexdigest() != sha256:
        # Microsoft updates a diagram now and then: azure.py list takes the new version
        print(f"{label}: the hash differs from corpus/azure.json, skipped", file=sys.stderr)
        return False
    path.write_bytes(data)
    print(f"{label}: downloaded", flush=True)
    return True


def fetch(only: str) -> int:
    """Download each diagram of the list, and its SVG of Visio, that the cache lacks or holds with another hash."""
    target = cache() / "azure"
    references = cache() / "reference" / "visio"
    target.mkdir(parents=True, exist_ok=True)
    references.mkdir(parents=True, exist_ok=True)
    failed = 0
    for entry in json.loads(LIST.read_text()):
        if only not in entry["name"]:
            continue
        failed += not fetched(entry["url"], entry["sha256"], target / f"{entry['name']}.vsdx", entry["name"])
        if "visio" in entry:
            failed += not fetched(entry["visio"]["url"], entry["visio"]["sha256"], references / f"{entry['name']}.svg", f"{entry['name']} (Visio SVG)")
    return 1 if failed else 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    commands = parser.add_subparsers(dest="command", required=True)
    listing = commands.add_parser("list", help="write corpus/azure.json")
    listing.add_argument("checkout", type=Path, help="a checkout of MicrosoftDocs/architecture-center")
    visio = commands.add_parser("visio", help="add the SVG of Visio of each diagram to corpus/azure.json")
    visio.add_argument("checkout", type=Path, help="a checkout of MicrosoftDocs/architecture-center")
    fetching = commands.add_parser("fetch", help="download the diagrams and their SVGs into the cache")
    fetching.add_argument("--only", default="", help="fetch only the names that contain this text")
    args = parser.parse_args()
    if args.command == "list":
        return make_list(args.checkout)
    if args.command == "visio":
        return add_visio(args.checkout)
    return fetch(args.only)


if __name__ == "__main__":
    sys.exit(main())
